def read_u16le(data, pos):
    return data[pos] | (data[pos + 1] << 8)

def read_sprite_table(base_addr, table, offset):
    pos = 0
    done = False
    while not done:
        row = table[pos]
        #print(f"# Row {row:02X}")
        pos += 1

        addr = read_u16le(table, pos)
        if addr == 0xFFFF:
            done = True

        #print(f"# Address: {addr:04X}")

        pos += 2
        row_done = False
        
        while not row_done:
            x = table[pos]
            len = table[pos + 1]
            id = table[pos + 2]

            #print(f"# X: {x:02X}, Len: {len:02X}, ID: {id:02X}")

            if id == 0x02:
                address = base_addr + pos + 2
                # Write out this format
                # { (0x02, 0x0F), 0x74000A },
                # where 0x02 = y, 0x0F = x and 0x74000A = address
                print(f"{{ (0x{row:02X}, 0x{x:02X}), 0x{address:06X} }},")

            if len == 0xFF:
                pos = (addr - 0x8000) - offset
                row_done = True
            else:
                pos += len


