    public static string GetTestDisplayName(MethodInfo methodInfo, object[] values)
    {
        if (values is [string input, byte[] expected])
            return $"{input} -> [{string.Join(", ", expected.Select(x => x.ToString("x02")))}]";

        return string.Join(", ", values);
    }

